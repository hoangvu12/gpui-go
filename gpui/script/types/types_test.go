package types_test

// The type checker's behaviour (ticket 63): the embedded .d.ts, the
// clear error when tsc is missing, and — when a tsc is available (an
// explicit one through GPUI_TYPESCRIPT or one it discovers) — that the
// clean surface fixture type-checks and the error sample is caught
// (misspelled style key, bad value, unknown prop, bad Class).
//
// tsc is not a dependency of the module and nothing installs it: the
// checker reports exactly where it looked when it finds none, and the
// tests that need it skip. GPUI_TYPESCRIPT points at one for CI or a
// developer machine (a tsc.js path or an executable).

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/hoangvu12/gpui-go/gpui/script"
	"github.com/hoangvu12/gpui-go/gpui/script/types"
)

func TestDTSIsEmbedded(t *testing.T) {
	dts := types.DTS()
	if !strings.HasPrefix(dts, "// Code generated by cmd/tsxdtsgen") {
		t.Fatalf("the embedded .d.ts does not carry its generated banner")
	}
	for _, want := range []string{
		"interface CSSProperties {", "interface HostProps {",
		"type Class =", "declare namespace JSX {", "declare function useState",
	} {
		if !strings.Contains(dts, want) {
			t.Errorf("the embedded .d.ts lacks %q", want)
		}
	}
}

func TestCheckerReportsMissingTypeScriptClearly(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "view.tsx"), []byte("export function App() { return <div>hi</div>; }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	c := types.NewChecker(dir, types.WithProgram(filepath.Join(dir, "missing", "tsc.js")))
	_, err := c.Check()
	if !errors.Is(err, types.ErrTypeScriptNotFound) {
		t.Fatalf("Check with a missing program = %v, want ErrTypeScriptNotFound", err)
	}
	for _, want := range []string{"tsc", "GPUI_TYPESCRIPT", "npm i -D typescript"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("the error does not mention %q: %v", want, err)
		}
	}
	if c.Available() {
		t.Errorf("Available() = true with a missing program")
	}
}

// resolveTypeScript returns a checker whose tsc is either the
// environment's or a discovered one, skipping the test when neither
// exists (nothing is installed; this machine has none in the repo).
func resolveTypeScript(t *testing.T, dir string) *types.Checker {
	t.Helper()
	c := types.NewChecker(dir)
	if c.Available() {
		return c
	}
	t.Skipf("no tsc available (set %s to a tsc.js to run this test)", types.EnvTypeScript)
	return nil
}

// sampleDir copies one testdata .tsx into a fresh directory the
// checker walks.
func sampleDir(t *testing.T, name string) string {
	t.Helper()
	src, err := os.ReadFile(filepath.Join("..", "testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, name), src, 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestCheckPassesTheSurfaceFixture(t *testing.T) {
	c := resolveTypeScript(t, sampleDir(t, "surface.tsx"))
	diags, err := c.Check()
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	for _, d := range diags {
		t.Errorf("unexpected diagnostic: %v", d)
	}
}

func TestCheckCatchesSurfaceErrors(t *testing.T) {
	c := resolveTypeScript(t, sampleDir(t, "errors.tsx"))
	diags, err := c.Check()
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	joined := ""
	for _, d := range diags {
		if d.Kind != "error" {
			continue
		}
		joined += d.String() + "\n"
	}
	for _, want := range []string{
		"'colr' does not exist",        // a misspelled style key
		`'"grid"' is not assignable`,   // a bad value
		`'"p-13px"' is not assignable`, // a bad class
		"'onClik' does not exist",      // an unknown prop
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("tsc did not catch %q; diagnostics:\n%s", want, joined)
		}
	}
	for _, d := range diags {
		if d.Line == 0 || d.Code == "" || !strings.HasSuffix(d.File, "errors.tsx") {
			t.Errorf("diagnostic without a position: %+v", d)
		}
	}
}

