package gpui

// This file is browser-core ticket 10 (hover enter/leave, spec D12): the
// per-element pointer boundary events and the window-exit event that
// clears hover when the pointer leaves the window, ported toward the
// browser rather than the pin wherever the two differ (D0: the browser
// wins):
//
//   - DOM pointerenter/pointerleave order. Chromium computes both
//     ancestor chains (target-first) and fires leave events child to
//     parent, then enter events parent to child
//     (third_party/blink/renderer/core/input/boundary_event_dispatcher.cc:
//     190-193 "Dispatch leave events, in child-to-parent order" and
//     :211-214 "Dispatch enter events, in parent-to-child order"), all
//     before the move event itself (pointer_event_manager.cc:1353-1365
//     ProcessCaptureAndPositionOfPointerEvent sends the boundary events
//     from inside SendMousePointerEvent, which then dispatches the
//     move). The port dispatches the same order as two sweeps over the
//     rendered frame's mouse listeners: a leave sweep in reverse
//     registration order (listeners register parent-before-child, so
//     reverse is innermost-first) and an enter sweep in registration
//     order (outermost-first), before the move's capture/bubble
//     traversal.
//   - Leaving the window. Chromium's kMouseLeave skips the hit test and
//     clears hover/active state with a null target
//     (core/input/event_handler.cc:1158-1165: "we avoid the hit test but
//     still clear the hover/active state", UpdateHoverActiveState(...,
//     nullptr)). The pin's Windows host only flips the window's hovered
//     flag on WM_MOUSELEAVE and never tells element dispatch
//     (reference/ce-source/crates/gpui_windows/src/events.rs:405-418,
//     the gap research browser-parity 03 §1 documents); the pin's own
//     MouseExitEvent (crates/gpui/src/interactive.rs:666-684 "A mouse
//     exit event from the platform, generated when the mouse leaves the
//     window") and its div hover clear (elements/div.rs:3674-3680) are
//     the intended receivers. The port now produces that event: the
//     host's WM_MOUSELEAVE/WM_NCMOUSELEAVE handler dispatches a
//     MouseExitEvent through the mouse input callback, and the dispatch
//     moves the tracked mouse position off window so every hit test
//     comes up empty and hover clears on every element.
//
// Hover is no longer suppressed by keyboard input (spec D12: "hover
// survives typing"): HitboxID.IsHovered ignores the input modality (the
// modality only still drives FocusVisible styles), and Chromium never
// clears hover on key events (core/input has no such link; the only
// keyboard hook into :hover is :focus-visible, §7 of the report).

import (
	"slices"
)

// MouseExitEvent is the platform's "the pointer left the window" event
// (the pin's interactive.rs:666-684 MouseExitEvent, generated by
// WM_MOUSELEAVE / WM_NCMOUSELEAVE on Windows through
// TrackMouseEvent). The Windows host learns the leave without
// coordinates, so Position carries the window's last tracked position
// (best effort) and PressedButton is unknown (nil); the dispatch
// itself moves the tracked position off window so hover clears on
// every element.
type MouseExitEvent struct {
	// Position is the last known position of the mouse relative to the
	// window (best effort; the leave itself carries no coordinates).
	Position Point
	// PressedButton is the button held when the pointer left, when
	// known (the Windows leave reports none).
	PressedButton *MouseButton
	// Modifiers were held down when the pointer left.
	Modifiers Modifiers
}

// PointerEnterEvent is the DOM pointerenter event (non-bubbling): it
// fires on an element when the pointer enters it, after it has fired
// on every entered ancestor (outermost first). Like the DOM event it
// precedes the pointermove that caused it.
type PointerEnterEvent struct {
	// Position is the pointer's window-local position at the transition.
	Position Point
	// Modifiers were held when the pointer entered.
	Modifiers Modifiers
}

// PointerLeaveEvent is the DOM pointerleave event (non-bubbling): it
// fires on an element when the pointer leaves it (or the window),
// before it fires on any exited ancestor (innermost first).
type PointerLeaveEvent struct {
	// Position is the pointer's window-local position at the transition
	// (the last known position when leaving the window).
	Position Point
	// Modifiers were held when the pointer left.
	Modifiers Modifiers
}

// hoverBoundarySweep is the internal marker event the hover-boundary
// dispatch sends through the rendered frame's mouse listeners: each
// element's boundary listener (interact.go paintMouseListeners) checks
// its own hover transition and fires its enter or leave listeners. It
// is never seen by user listeners.
type hoverBoundarySweep struct {
	// enter selects the enter sweep (outermost first) over the leave
	// sweep (innermost first).
	enter bool
	// position is the pointer's position at the transition.
	position Point
	// modifiers were held at the transition.
	modifiers Modifiers
}

// offWindowMousePosition is the tracked mouse position while the
// pointer is outside the window: no hitbox can contain it (far outside
// every window-local bound, including bounds with negative origins),
// so the hit test comes up empty and hover clears on every element —
// Chromium's null-target leave (event_handler.cc:1158-1165).
var offWindowMousePosition = Point{X: -1e9, Y: -1e9}

// dispatchHoverBoundaryEvents runs the pointer boundary sweeps against
// the rendered frame's mouse listeners: first the leave sweep in
// reverse registration order (mouse listeners register
// parent-before-child, so reverse is innermost-first — the DOM's
// child-to-parent leave order), then the enter sweep in registration
// order (outermost-first — the DOM's parent-to-child enter order).
// Every listener is invoked regardless of propagation breaks: the
// sweeps are an ordering device for non-bubbling per-element events,
// not a capture/bubble traversal (boundary_event_dispatcher.cc:190-214
// dispatches each chain member exactly once, in chain order). position
// and modifiers are the dispatching event's (the move's, or the exit
// event's last-known position).
func (w *Window) dispatchHoverBoundaryEvents(position Point, modifiers Modifiers, app *App) {
	fs := focusState(w)
	if fs.rendered == nil {
		return
	}
	listeners := append([]mouseListener(nil), fs.rendered.mouseListeners...)
	sweep := &hoverBoundarySweep{position: position, modifiers: modifiers}
	// The leave sweep: innermost first.
	sweep.enter = false
	for i := len(listeners) - 1; i >= 0; i-- {
		listeners[i](sweep, DispatchBubble, w, app)
	}
	// The enter sweep: outermost first.
	sweep.enter = true
	for _, listener := range listeners {
		listener(sweep, DispatchCapture, w, app)
	}
}

// deferHoverBoundarySweep schedules one deferred boundary sweep for the
// frame under construction (the layout-change path): when an element
// paints with a hover answer that differs from its retained boundary
// state (the pointer did not move; layout moved the element under or
// away from the stationary mouse), the transition is reported by the
// same ordered sweeps once the frame's effects flush, like the pinned
// OnHover defer (div.rs:3629-3657). One deferred sweep serves every
// element of the frame; the pending flag deduplicates.
func (w *Window) deferHoverBoundarySweep(app *App) {
	st := interactStateOf(w)
	if st.boundarySweepPending {
		return
	}
	st.boundarySweepPending = true
	w.Defer(app, func(w *Window, app *App) {
		st := interactStateOf(w)
		st.boundarySweepPending = false
		w.dispatchHoverBoundaryEvents(w.TrackedMousePosition(), w.Modifiers(), app)
	})
}

// paintBoundaryListeners is one element's pointerenter/pointerleave
// registration on the frame under construction (called from
// paintMouseListeners): the element's hitbox, its retained hover state
// and its enter/leave listeners. The closure reacts to the internal
// sweep marker only.
func (d *DivElement) paintBoundaryListeners(hitbox Hitbox, es *InteractiveElementState, w *Window, app *App) {
	if len(d.pointerEnterListeners) == 0 && len(d.pointerLeaveListeners) == 0 {
		return
	}
	if es.hoverBoundaryState == nil {
		es.hoverBoundaryState = new(bool)
	}
	wasHovered := es.hoverBoundaryState
	enterListeners := slices.Clone(d.pointerEnterListeners)
	leaveListeners := slices.Clone(d.pointerLeaveListeners)
	box := hitbox
	w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
		sweep, ok := event.(*hoverBoundarySweep)
		if !ok {
			return
		}
		// Hover is the hit-test answer; an active drag suppresses it the
		// way the pin's hover styles and OnHover do (computeStyleInternal,
		// interact.go), matching the browser, whose drag loop delivers no
		// pointer boundary events at all.
		hovered := !app.HasActiveDrag() && box.IsHovered(w)
		if hovered == *wasHovered {
			return
		}
		// Each sweep owns only its own half of the transition: the leave
		// sweep (innermost-first) must not consume an enter transition, or
		// the enter sweep that follows would see no change.
		if hovered != sweep.enter {
			return
		}
		*wasHovered = hovered
		if hovered {
			e := &PointerEnterEvent{Position: sweep.position, Modifiers: sweep.modifiers}
			for _, listener := range enterListeners {
				listener(e, w, app)
			}
		} else {
			e := &PointerLeaveEvent{Position: sweep.position, Modifiers: sweep.modifiers}
			for _, listener := range leaveListeners {
				listener(e, w, app)
			}
		}
	})
	// The layout-change path: a stationary mouse whose layout moved
	// under it reports the transition through one deferred ordered
	// sweep (the OnHover pattern, div.rs:3629-3657).
	if hovered := !app.HasActiveDrag() && hitbox.IsHovered(w); hovered != *wasHovered {
		w.deferHoverBoundarySweep(app)
	}
}
