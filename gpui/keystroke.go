// KeybindingKeystroke represents a keystroke that can be used in
// keybindings and displayed to the user (platform/keystroke.rs
// KeybindingKeystroke). On Windows it carries a display key and display
// modifiers alongside the GPUI representation: a ctrl-@ keystroke has
// inner.modifiers as control and display modifiers as control-shift,
// inner.key as @ and display key as 2.
type KeybindingKeystroke struct {
	// inner is the GPUI representation of the keystroke.
	inner Keystroke
	// displayModifiers are the modifiers to display (Windows).
	displayModifiers Modifiers
	// displayKey is the key to display (Windows).
	displayKey string
}

// NewKeybindingKeystroke creates a keybinding keystroke from the given
// keystroke, without any platform-specific mapping
// (KeybindingKeystroke::from_keystroke).
func NewKeybindingKeystroke(inner Keystroke) KeybindingKeystroke {
	return KeybindingKeystroke{
		inner:            inner,
		displayModifiers: inner.Modifiers,
		displayKey:       inner.Key,
	}
}

// NewKeybindingKeystrokeWithDisplay creates a keybinding keystroke with
// explicit Windows display fields (KeybindingKeystroke::new).
func NewKeybindingKeystrokeWithDisplay(inner Keystroke, displayModifiers Modifiers, displayKey string) KeybindingKeystroke {
	return KeybindingKeystroke{inner: inner, displayModifiers: displayModifiers, displayKey: displayKey}
}

// Inner returns the GPUI representation of the keystroke.
func (k KeybindingKeystroke) Inner() Keystroke { return k.inner }

// Modifiers returns the modifiers to display.
func (k KeybindingKeystroke) Modifiers() Modifiers { return k.displayModifiers }

// Key returns the key to display.
func (k KeybindingKeystroke) Key() string { return k.displayKey }

// SetModifiers sets the modifiers. On Windows this modifies both the
// inner and the display modifiers.
func (k *KeybindingKeystroke) SetModifiers(modifiers Modifiers) {
	k.inner.Modifiers = modifiers
	k.displayModifiers = modifiers
}

// SetKey sets the key. On Windows this modifies both the inner and the
// display keys.
func (k *KeybindingKeystroke) SetKey(key string) {
	k.displayKey = key
	k.inner.Key = key
}

// Unparse produces a representation of this key that ParseKeystroke can
// understand (the Windows display spelling).
func (k KeybindingKeystroke) Unparse() string {
	var b strings.Builder
	if k.displayModifiers.Function {
		b.WriteString("fn-")
	}
	if k.displayModifiers.Control {
		b.WriteString("ctrl-")
	}
	if k.displayModifiers.Alt {
		b.WriteString("alt-")
	}
	if k.displayModifiers.Platform {
		b.WriteString("win-")
	}
	if k.displayModifiers.Shift {
		b.WriteString("shift-")
	}
	b.WriteString(k.displayKey)
	return b.String()
}

// RemoveKeyChar removes the key_char.
func (k *KeybindingKeystroke) RemoveKeyChar() { k.inner.KeyChar = "" }

// String renders the display spelling.
func (k KeybindingKeystroke) String() string { return k.Unparse() }

// matchKeystrokes checks if the given keystrokes match this binding.
// It reports whether the keystrokes match at all, and whether more
// keystrokes are still required to complete the binding (Option<bool>
// in the reference: no match, a prefix, or a full match).
func (k *KeybindingKeystroke) matchKeystrokes(typed []Keystroke) (matched bool, pending bool) {
	binding := []KeybindingKeystroke{*k}
	if len(binding) < len(typed) {
		return false, false
	}
	for i := range typed {
		if !typed[i].ShouldMatch(&binding[i]) {
			return false, false
		}
	}
	return true, len(binding) > len(typed)
}

// ---------------------------------------------------------------------------
// Keyboard input events
// ---------------------------------------------------------------------------

// KeyDownEvent is a key down platform event (platform.rs KeyDownEvent).
type KeyDownEvent struct {
	// Keystroke is the key that was pressed.
	Keystroke Keystroke
	// IsHeld reports whether the key is auto-repeating (the Windows
	// repeat bit of WM_KEYDOWN's lparam).
	IsHeld bool
	// PreferCharacterInput reports that the platform prefers text input
	// over a key binding for this keystroke (dead keys and
	// layout-dependent AltGr characters set this on Windows).
	PreferCharacterInput bool
}

// KeyUpEvent is a key up platform event (platform.rs KeyUpEvent).
type KeyUpEvent struct {
	// Keystroke is the key that was released.
	Keystroke Keystroke
}

// ModifiersChangedEvent is a change of the keyboard modifier state
// (interactive.rs ModifiersChangedEvent).
type ModifiersChangedEvent struct {
	// Modifiers is the new state of the modifier keys.
	Modifiers Modifiers
	// Capslock is the state of the capslock key.
	Capslock Capslock
}

// PlatformInput is the keyboard platform input the window dispatch
// consumes (the keyboard members of platform.rs PlatformInput). Mouse,
// touch and IME composition inputs arrive with their tickets.
type PlatformInput interface {
	platformInput()
}

func (*KeyDownEvent) platformInput()          {}
func (*KeyUpEvent) platformInput()            {}
func (*ModifiersChangedEvent) platformInput() {}

// ---------------------------------------------------------------------------
// Keyboard mapper
// ---------------------------------------------------------------------------

// KeyboardMapper maps a parsed keystroke into its keybinding form
// (PlatformKeyboardMapper in the reference). MapKeyEquivalent is the
// seam a platform uses to translate user-facing bindings through the
// actual keyboard layout.
type KeyboardMapper interface {
	// MapKeyEquivalent maps the keystroke, using key equivalents from a
	// US layout when useKeyEquivalents is set.
	MapKeyEquivalent(keystroke Keystroke, useKeyEquivalents bool) KeybindingKeystroke
}

// DummyKeyboardMapper is the identity mapper (DummyKeyboardMapper in
// the reference): bindings keep exactly the keystroke the author wrote.
type DummyKeyboardMapper struct{}

// MapKeyEquivalent implements KeyboardMapper.
func (DummyKeyboardMapper) MapKeyEquivalent(keystroke Keystroke, _ bool) KeybindingKeystroke {
	return NewKeybindingKeystroke(keystroke)
}
