// cursorStyleRequest is window.rs:748-753 CursorStyleRequest: a style
// for a hitbox, or (hasHitbox false) for the whole window.
type cursorStyleRequest struct {
	hitboxID  uint64
	hasHitbox bool
	style     CursorStyle
}

// frameCursorRequests are one frame's cursor requests (window.rs Frame
// cursor_styles).
type frameCursorRequests struct {
	frame    *renderedFrame
	requests []cursorStyleRequest
}

// interactWindowState is the window's interaction side state, touched
// only on the foreground thread: the frame-scoped cursor requests (the
// pinned Frame::cursor_styles, keyed by the dispatch frame they were
// registered on — at most the rendered frame and the one under
// construction), the frame whose hitboxes the paint-time hit test was
// computed from, the hidden-subtree prepaint depth, and the last cursor
// the reset resolved (the test-support observable of reset_cursor_style).
type interactWindowState struct {
	cursorFrames      []frameCursorRequests
	paintHitTestFrame *renderedFrame
	hiddenDepth       int
	resolvedCursor    CursorStyle
	resolvedCursorSet bool
}

// interactWindowStates is the per-window registry (the windowDrawStates
// pattern). Closed windows are pruned when a new entry is created.
var interactWindowStates = map[*Window]*interactWindowState{}

// interactStateOf returns (creating when absent) the window's state.
func interactStateOf(w *Window) *interactWindowState {
	if st, ok := interactWindowStates[w]; ok {
		return st
	}
	for other := range interactWindowStates {
		if !windowIsOpen(other) {
			delete(interactWindowStates, other)
		}
	}
	st := &interactWindowState{}
	interactWindowStates[w] = st
	return st
}

// lastInputWasKeyboard is window.rs Window::last_input_was_keyboard.
func lastInputWasKeyboard(w *Window) bool { return inputState(w).lastInputWasKeyboard }

// lastInputWasTouch is window.rs Window::last_input_was_touch (the
// Windows port has no touch input source, so it stays false).
func lastInputWasTouch(w *Window) bool {
	return inputState(w).lastInputModality == inputModalityTouch
}

// beginPlatformInputDispatch is the head of window.rs:5739-5760
// dispatch_event: track the input modality (a key down switches to the
// keyboard, a mouse move or down to the mouse; other events keep it)
// and refresh the window when it changed (focus-visible styles and the
// hover suppression read it), then start propagation and clear the
// prevent-default flag.
func (w *Window) beginPlatformInputDispatch(event any, app *App) {
	is := inputState(w)
	old := is.lastInputModality
	switch event.(type) {
	case *KeyDownEvent:
		is.lastInputModality = inputModalityKeyboard
	case *MouseMoveEvent, *MouseDownEvent:
		is.lastInputModality = inputModalityMouse
	}
	is.lastInputWasKeyboard = is.lastInputModality == inputModalityKeyboard
	if is.lastInputModality != old {
		w.requestRefresh()
	}
	app.propagateEvent = true
	is.defaultPrevented = false
}

// hiddenPrepaintDepth reports how many hidden divs enclose the element
// being prepainted.
func hiddenPrepaintDepth(w *Window) int {
	if st, ok := interactWindowStates[w]; ok {
		return st.hiddenDepth
	}
	return 0
}

// withHiddenPrepaint runs f (a hidden div's children prepaint) inside
// the hidden-subtree scope: the pinned paint never reaches a hidden
// div's children (div.rs:3021-3023), so their prepaint-registered
// dispatch state is suppressed.
func withHiddenPrepaint(w *Window, hidden bool, f func()) {
	if !hidden {
		f()
		return
	}
	st := interactStateOf(w)
	st.hiddenDepth++
	defer func() { st.hiddenDepth-- }()
	f()
}

// ensurePaintHitTest computes the window's hit test against the frame
// under construction once its prepaint has inserted every hitbox (the
// pinned draw computes it between prepaint and paint, window.rs:3459,
// so paint-time hover styles and listener setup see the new frame's
// hitboxes). The port's draw path does not run that step, so the first
// div paint of a frame runs it.
func ensurePaintHitTest(w *Window) {
	fs := focusState(w)
	if fs.next == nil {
		return
	}
	st := interactStateOf(w)
	if st.paintHitTestFrame == fs.next {
		return
	}
	st.paintHitTestFrame = fs.next
	is := inputState(w)
	is.mouseHitTest = fs.next.hitTestAt(is.mousePosition)
}

