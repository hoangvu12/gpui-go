// withHiddenPrepaint runs f (a hidden div's children prepaint) inside
// the hidden-subtree scope: the pinned paint never reaches a hidden
// div's children (div.rs:3021-3023), so their prepaint-registered
// dispatch state is suppressed.
func withHiddenPrepaint(w *Window, hidden bool, f func()) {
	if !hidden {
		f()
		return
	}
	st := interactStateOf(w)
	st.hiddenDepth++
	defer func() { st.hiddenDepth-- }()
	f()
}

// withInertPrepaint runs f (an inert div's children prepaint) inside
// the inert-subtree scope (browser-core ticket 14): the children's
// prepaint-registered dispatch state is suppressed (no tab stops, no
// keyboard clicks, no key listeners, suppressed focus) and their
// hitboxes carry the inert flag the hit test skips (mouseevent.go
// hitTestAt) — pointer-events: none, computed_style.h:1862-1867. The
// children still paint (inertness is not visibility).
func withInertPrepaint(w *Window, inert bool, f func()) {
	if !inert {
		f()
		return
	}
	st := interactStateOf(w)
	st.inertDepth++
	defer func() { st.inertDepth-- }()
	f()
}

// ensurePaintHitTest computes the window's hit test against the frame
// under construction once its prepaint has inserted every hitbox (the
// pinned draw computes it between prepaint and paint, window.rs:3459,
// so paint-time hover styles and listener setup see the new frame's
// hitboxes). The port's draw path does not run that step, so the first
// div paint of a frame runs it. Browser-core ticket 11: the effective
// hit test is the capture chain while a pointer capture is active
// (pointercapture.go currentHitTest), so the captured element keeps
// its hover styles wherever the pointer is.
func ensurePaintHitTest(w *Window) {
	fs := focusState(w)
	if fs.next == nil {
		return
	}
	st := interactStateOf(w)
	if st.paintHitTestFrame == fs.next {
		return
	}
	st.paintHitTestFrame = fs.next
	is := inputState(w)
	is.mouseHitTest = w.currentHitTest(fs.next)
}

