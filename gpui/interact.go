// computeStyleInternal is div.rs:3904-4063 compute_style_internal: the
// base style, then the focus styles, the group-hover and hover styles
// (not during a drag), the drag cursor, and the group-active and active
// styles. hitbox is nil before paint (hover then comes from the retained
// hover state); es is nil for an id-less element. The drag-over styles
// are drop_listener.go refineDragOver; style transitions are not ported.
func (d *DivElement) computeStyleInternal(hitbox *Hitbox, es *InteractiveElementState, w *Window, app *App) Style {
	style := DefaultStyle()
	style.refineBoxed(d.Styled.storage(), &d.styleBoxes)

	if d.focusHandle != nil {
		handle := *d.focusHandle
		if d.inFocusStyle != nil && handle.WithinFocused(w) {
			style.Refine(d.inFocusStyle)
		}
		if d.focusStyle != nil && handle.IsFocused(w) {
			style.Refine(d.focusStyle)
		}
		// Browser-core ticket 12 (spec D12): the condition is
		// Chromium's :focus-visible test (focusVisibleMatches — the
		// focus origin and the unmodified-key flag,
		// selector_checker.cc:3888-3901), not the pin's last-keyboard-
		// input modality (window.rs:5748): a click focus shows no ring,
		// a Tab focus does, and a modified key (Ctrl+S) after a click
		// leaves the ring off; a mouse move no longer hides it either.
		if d.focusVisibleStyle != nil && handle.IsFocused(w) && focusVisibleMatches(w) {
			style.Refine(d.focusVisibleStyle)
		}
	}

	if !app.HasActiveDrag() {
		if group := d.groupHoverStyle; group != nil {
			hovered := false
			if id, ok := groupHitboxGet(group.Group, app); ok {
				hovered = !lastInputWasTouch(w) && id.IsHovered(w)
			} else if es != nil && es.hoverState != nil {
				hovered = es.hoverState.groupIsActive(w)
			}
			if hovered {
				style.Refine(&group.Style)
			}
		}
		if d.hoverStyle != nil {
			hovered := false
			if hitbox != nil {
				hovered = !lastInputWasTouch(w) && hitbox.IsHovered(w)
			} else if es != nil && es.hoverState != nil {
				hovered = es.hoverState.elementIsActive(w)
			}
			if hovered {
				style.Refine(d.hoverStyle)
			}
		}
	}

	if hitbox != nil {
		if drag := app.ActiveDrag(); drag != nil {
			d.refineDragOver(&style, hitbox, drag, w, app)
			// style.mouse_cursor = drag.cursor_style (div.rs:4020).
			if drag.CursorStyle != nil {
				cursor := *drag.CursorStyle
				style.MouseCursor = &cursor
			} else {
				style.MouseCursor = nil
			}
		}
	}

	if es != nil {
		clicked := es.clicked()
		if clicked.Group && d.groupActiveStyle != nil {
			style.Refine(&d.groupActiveStyle.Style)
		}
		if d.activeStyle != nil && clicked.Element {
			style.Refine(d.activeStyle)
		}
	}

	// The default focus ring (browser-core ticket 48): the CSS
	// initial outline-style: auto is the UA :focus-visible rule's ring
	// (html.css:1701-1703, `:focus-visible { outline: auto 1px
	// -webkit-focus-ring-color }`): it materializes — becomes the
	// focus ring kind, which the paint path draws as the single-stroke
	// default ring — on a focused element whose focus passes the
	// :focus-visible test (the same focusVisibleMatches the
	// FocusVisible refinement uses: a click focus draws nothing), and
	// drops to none everywhere else, so an author outline (or
	// outline-none) wins the way author styles override the UA sheet.
	// The text-input arm (Chromium always shows the ring on text entry)
	// and the accessibility override stay future work, like the
	// :focus-visible test's own.
	if style.Outline.Kind == OutlineAuto {
		focused := d.focusHandle != nil && (*d.focusHandle).IsFocused(w) && focusVisibleMatches(w)
		if focused {
			style.Outline.Kind = OutlineFocusRing
		} else {
			style.Outline.Kind = OutlineNone
		}
	}

	// The forced-colours pass (browser-core 29) runs last, like
	// Chromium's adjuster after the cascade (style_adjuster.cc:1326-
	// 1327): the fully resolved style maps onto the system palette when
	// the pass is active and the element did not opt out.
	applyForcedColorsToStyle(&style, app)
	return style
}

