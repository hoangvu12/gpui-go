// cursorRequestFrame returns the frame under construction, panicking
// outside a draw (the pinned debug_assert_paint).
func cursorRequestFrame(w *Window, what string) *renderedFrame {
	if w == nil {
		panic(fmt.Sprintf("gpui: %s requires a live window", what))
	}
	fs := focusState(w)
	if fs.next == nil {
		panic(fmt.Sprintf("gpui: %s requires a frame under construction (paint)", what))
	}
	return fs.next
}

// appendCursorRequest records one request on the frame under
// construction, dropping requests of frames that are neither rendered
// nor being built.
func appendCursorRequest(w *Window, frame *renderedFrame, request cursorStyleRequest) {
	st := interactStateOf(w)
	for i := range st.cursorFrames {
		if st.cursorFrames[i].frame == frame {
			st.cursorFrames[i].requests = append(st.cursorFrames[i].requests, request)
			return
		}
	}
	rendered := focusState(w).rendered
	kept := st.cursorFrames[:0]
	for _, f := range st.cursorFrames {
		if f.frame == rendered {
			kept = append(kept, f)
		}
	}
	st.cursorFrames = append(kept, frameCursorRequests{frame: frame, requests: []cursorStyleRequest{request}})
}

// SetCursorStyle requests the cursor shown while the hitbox is hovered
// (window.rs:3844-3850 set_cursor_style). Paint phase only.
func (w *Window) SetCursorStyle(style CursorStyle, hitbox *Hitbox) {
	if hitbox == nil {
		panic("gpui: SetCursorStyle requires a hitbox")
	}
	frame := cursorRequestFrame(w, "SetCursorStyle")
	appendCursorRequest(w, frame, cursorStyleRequest{hitboxID: hitbox.id, hasHitbox: true, style: style})
}

// SetWindowCursorStyle requests the cursor for the whole window, taking
// precedence over every hitbox request (window.rs:3856-3862
// set_window_cursor_style). Paint phase only.
func (w *Window) SetWindowCursorStyle(style CursorStyle) {
	frame := cursorRequestFrame(w, "SetWindowCursorStyle")
	appendCursorRequest(w, frame, cursorStyleRequest{style: style})
}

// frameCursorStyle is window.rs:1200-1213 Frame::cursor_style: walking
// the requests newest first, a window request wins outright; otherwise
// the newest request whose hitbox is hovered (ignoring the keyboard
// modality) decides.
func frameCursorStyle(w *Window, frame *renderedFrame) (CursorStyle, bool) {
	st, ok := interactWindowStates[w]
	if !ok || frame == nil {
		return CursorArrow, false
	}
	for _, f := range st.cursorFrames {
		if f.frame != frame {
			continue
		}
		var found *CursorStyle
		for i := len(f.requests) - 1; i >= 0; i-- {
			request := f.requests[i]
			if !request.hasHitbox {
				return request.style, true
			}
			if found == nil && HitboxID(request.hitboxID).isHoveredIgnoringLastInput(w) {
				style := request.style
				found = &style
			}
		}
		if found != nil {
			return *found, true
		}
		return CursorArrow, false
	}
	return CursorArrow, false
}

