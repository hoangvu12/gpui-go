// appGroupHitboxes is the application's GroupHitboxes global: the stack
// of hitbox ids per group name, pushed by a grouped div around its
// children's paint. Foreground thread only; emptied stacks are removed.
var appGroupHitboxes = map[*App]map[string][]HitboxID{}

// groupHitboxGet is div.rs:4553 GroupHitboxes::get: the innermost
// hitbox of the named group being painted.
func groupHitboxGet(name string, app *App) (HitboxID, bool) {
	stacks := appGroupHitboxes[app]
	stack := stacks[name]
	if len(stack) == 0 {
		return 0, false
	}
	return stack[len(stack)-1], true
}

// groupHitboxPush is div.rs:4561 GroupHitboxes::push.
func groupHitboxPush(name string, id HitboxID, app *App) {
	stacks := appGroupHitboxes[app]
	if stacks == nil {
		stacks = map[string][]HitboxID{}
		appGroupHitboxes[app] = stacks
	}
	stacks[name] = append(stacks[name], id)
}

// groupHitboxPop is div.rs:4569 GroupHitboxes::pop.
func groupHitboxPop(name string, app *App) {
	stacks := appGroupHitboxes[app]
	stack := stacks[name]
	if len(stack) == 0 {
		return
	}
	stack = stack[:len(stack)-1]
	if len(stack) == 0 {
		delete(stacks, name)
		if len(stacks) == 0 {
			delete(appGroupHitboxes, app)
		}
		return
	}
	stacks[name] = stack
}

