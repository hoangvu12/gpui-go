// paintHoverGroupHandler is div.rs:3798-3814: while a group-hover style
// names a group being painted, a mouse move that flips the group's
// hover notifies the current view. It registers before the hidden
// check, so an invisible group-hover target still becomes visible.
func (d *DivElement) paintHoverGroupHandler(w *Window, app *App) {
	if d.groupHoverStyle == nil {
		return
	}
	id, ok := groupHitboxGet(d.groupHoverStyle.Group, app)
	if !ok {
		return
	}
	wasHovered := id.IsHovered(w)
	notify := currentViewNotifier(w)
	w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
		if _, isMove := event.(*MouseMoveEvent); !isMove {
			return
		}
		hovered := id.IsHovered(w)
		if phase == DispatchCapture && hovered != wasHovered {
			notify(w, app)
		}
	})
}

// registerDivKeyboardClick registers the element's click listeners on
// its dispatch node (browser-core ticket 12): the keyboard activation
// default (key_default_action.go defaultKeyboardActivation) reads them
// from the FOCUSED node — the gate the pin's focus-gated registration
// implemented (div.rs:3512-3577) — and fires them through the focused
// node's whole ancestor path, the DOM's bubbling simulated click
// (Chromium HTMLElement::HandleKeyboardActivation, html_element.cc:
// 4314-4338, the button override at html_button_element.cc:285-296;
// DispatchSimulatedClick's propagation, event_dispatcher.cc:163-187).
// Every clickable element registers (its node's position in the tree
// is what the dispatch walks); suppressed subtrees register nothing.
func registerDivKeyboardClick(w *Window, d *DivElement, hitbox Hitbox, es *InteractiveElementState) {
	if es == nil || (len(d.clickListeners) == 0 && len(d.auxClickListeners) == 0) {
		return
	}
	tree := currentDispatchTree(w)
	tree.SetClickActivation(nodeClickActivation{
		listeners: slices.Clone(d.clickListeners),
		clicked:   es.clicked(),
		bounds:    hitbox.Bounds,
	})
}

// paintMouseListeners is div.rs:3253-3764 paint_mouse_listeners, bounded
// to the port's features (mouse pressure / exit listeners and tooltips
// are not ported; the keyboard click registers at prepaint,
// registerDivKeyboardClick). path is the element's global id key (the
// hitbox's ownerPath — the click dispatch resolves its target chain by
// it, browser-core ticket 12).
func (d *DivElement) paintMouseListeners(hitbox Hitbox, path string, es *InteractiveElementState, w *Window, app *App) {
	// A focusable element transfers focus on a hovered mouse down unless
	// the default action was prevented (div.rs:3266-3282). Browser-core
	// ticket 12 (spec D12): the innermost-wins signal between focusable
	// elements is a window-internal flag, not the DOM event's
	// preventDefault — the pin's PreventDefault call made every
	// mousedown on a focusable element report default-prevented, where
	// Chrome's mouse focus (HandleMouseFocus, mouse_event_manager.cc:
	// 537-636, run after the listeners at event_handler.cc:998-1001)
	// leaves the event unprevented. The focus is a mouse-origin focus
	// (focusWithOrigin), so the focus-visible styles stay off until the
	// next unmodified key.
	if d.focusHandle != nil {
		handle := *d.focusHandle
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isDown := event.(*MouseDownEvent); !isDown {
				return
			}
			if phase == DispatchBubble && box.IsHovered(w) && !w.DefaultPrevented() && !claimFocusTransfer(w) {
				w.focusWithOrigin(handle, focusOriginMouse)
			}
		})
	}

	// The typed mouse-family listeners (div.rs:3284-3331: the
	// registration closure captures this element's hitbox and forwards
	// the phase; the listener decides what the hitbox gates).
	for _, listener := range d.mouseDownListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.mouseUpListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.mouseMoveListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.scrollWheelListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.pinchListeners {
		registerMouseListener(w, listener, hitbox)
	}

	// The hover-state tracker (div.rs:3333-3358): a captured mouse move
	// that flips the element's hover updates the retained hover state
	// and notifies the current view. Browser-core ticket 10: the window
	// exit (MouseExitEvent) also flips it off — the dispatch clears the
	// hit test before the listeners run, so hovered reads false and the
	// repaint drops the hover style (the pin clears hover styles the
	// same way on its platform's MouseExitEvent; Chromium's kMouseLeave
	// clears hover with a null target, event_handler.cc:1158-1165).
	_, hasBaseCursor := d.Styled.storage().MouseCursor.Get()
	if d.hoverStyle != nil || hasBaseCursor {
		var hoverState *ElementHoverState
		if d.hoverStyle != nil && es != nil {
			hoverState = es.hoverState
		}
		notify := currentViewNotifier(w)
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			switch event.(type) {
			case *MouseMoveEvent, *MouseExitEvent:
			default:
				return
			}
			hovered := box.IsHovered(w)
			wasHovered := hoverState != nil && hoverState.Element
			if phase == DispatchCapture && hovered != wasHovered && hoverState != nil {
				hoverState.Element = hovered
				notify(w, app)
			}
		})
	}

	// The group-hover tracker (div.rs:3360-3381). Browser-core ticket 10:
	// the window exit clears it too (the hit test is empty by then).
	if group := d.groupHoverStyle; group != nil {
		if id, ok := groupHitboxGet(group.Group, app); ok {
			var hoverState *ElementHoverState
			if es != nil {
				hoverState = es.hoverState
			}
			notify := currentViewNotifier(w)
			w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
				switch event.(type) {
				case *MouseMoveEvent, *MouseExitEvent:
				default:
					return
				}
				groupHovered := id.IsHovered(w)
				wasGroupHovered := hoverState != nil && hoverState.Group
				if phase == DispatchCapture && groupHovered != wasGroupHovered && hoverState != nil {
					hoverState.Group = groupHovered
					notify(w, app)
				}
			})
		}
	}

	var dragCursorStyle *CursorStyle
	if cursor, ok := d.Styled.storage().MouseCursor.Get(); ok {
		dragCursorStyle = &cursor
	}
	dragListener := d.dragListener
	clickListeners := slices.Clone(d.clickListeners)
	auxClickListeners := slices.Clone(d.auxClickListeners)

	// The drop listeners (div.rs:3391-3445): on a bubbled mouse up with an
	// active drag the element's CanDrop predicate accepts, the first
	// listener of the drag value's type whose own can-drop predicate
	// passes (or, without one, with this element hovered) stops the drag,
	// receives the value, refreshes and stops propagation. A refusal
	// leaves the drop to the enclosing targets. Browser-core ticket 16:
	// the same query answers the dragenter/dragover events — a matching,
	// hovered listener marks the drag session accepted (Chromium's
	// dragover acceptance is a cancelled event; the pin's drop listener
	// is this port's acceptance twin), so the drop lands and the OLE
	// drag loop reports COPY only over a target that would take it.
	if len(d.dropListeners) > 0 {
		listeners := append([]typedDropListener(nil), d.dropListeners...)
		canDropPredicate := d.canDropPredicate
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			up, isUp := event.(*MouseUpEvent)
			_, isOver := event.(*DragOverEvent)
			_, isEnter := event.(*DragEnterEvent)
			if !isUp && !isOver && !isEnter {
				return
			}
			if phase != DispatchBubble {
				return
			}
			drag := app.ActiveDrag()
			if drag == nil {
				return
			}
			if canDropPredicate != nil && !canDropPredicate(drag.Value, &box, w, app) {
				return
			}
			for _, listener := range listeners {
				if !dropListenerPayloadMatches(drag.Value, listener.payloadType) {
					continue
				}
				if listener.canDrop != nil {
					if !listener.canDrop(drag.Value, &box, w, app) {
						continue
					}
				} else if !box.IsHovered(w) {
					continue
				}
				if isUp {
					// The mouse-up arm: the value delivery (div.rs's drop arm).
					value, _ := app.StopDrag(w)
					if listener.onDrop != nil {
						listener.onDrop(value, up, w, app)
					}
					w.requestRefresh()
					app.StopPropagation()
				} else {
					// The dragenter/dragover arm (browser-core ticket 16):
					// a matching, hovered listener marks the session accepted
					// without consuming the event — the DOM acceptance is the
					// event's own cancellation, this marks the pin's twin.
					dragSessionOf(w).accepted = true
				}
				break
			}
		})
	}

	if es == nil {
		return
	}

	if len(clickListeners) > 0 || len(auxClickListeners) > 0 || dragListener != nil {
		pending := es.pendingMouseDownCell()
		clicked := es.clicked()
		box := hitbox
		hasAuxClickListeners := len(auxClickListeners) > 0

		// A hovered left press (any press with aux-click listeners)
		// becomes the pending mouse down (div.rs:3467-3480). Browser-core
		// ticket 11: a pointer cancel (WM_CAPTURECHANGED — another window
		// took the mouse capture mid-press) drops the pending press in the
		// capture phase, so the release that never arrives leaves no
		// button stuck and no click fires later (Chromium's pointercancel
		// ends the press sequence).
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isCancel := event.(*PointerCancelEvent); isCancel {
				if phase == DispatchCapture && pending.event != nil {
					pending.event = nil
					w.requestRefresh()
				}
				return
			}
			down, isDown := event.(*MouseDownEvent)
			if !isDown {
				return
			}
			if phase == DispatchBubble && (down.Button == MouseButtonLeft || hasAuxClickListeners) && box.IsHovered(w) {
				pressed := *down
				pending.event = &pressed
				// The armed chain entry (browser-core ticket 12): the
				// window-level click dispatch's press chain gains this
				// element — the elements whose arms ran, innermost-first
				// (this is the bubble phase), so a stopped mousedown or a
				// block-mouse overlay keeps the un-armed ancestors out of
				// the click's target set.
				armMouseClick(w, path)
				w.requestRefresh()
			}
		})

		// A bubbled move past the drag threshold with the left button
		// pending starts the drag once (div.rs:3482-3510). Browser-core
		// ticket 16: the drag start fires dragstart on the source's chain
		// first, and a prevented dragstart cancels the start (Chromium's
		// TryStartDrag, mouse_event_manager.cc:1051) — the press stays
		// clickable, exactly a drag that never started.
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			move, isMove := event.(*MouseMoveEvent)
			if !isMove || phase == DispatchCapture || dragListener == nil {
				return
			}
			mouseDown := pending.event
			if mouseDown == nil {
				return
			}
			if app.HasActiveDrag() || mouseDown.Button != MouseButtonLeft {
				return
			}
			dx := float64(move.Position.X - mouseDown.Position.X)
			dy := float64(move.Position.Y - mouseDown.Position.Y)
			if math.Hypot(dx, dy) <= dragThreshold {
				return
			}
			listenedDrag := dragListener
			listenedCursor := dragCursorStyle
			cursorOffset := Point{X: move.Position.X - box.Bounds.Origin.X, Y: move.Position.Y - box.Bounds.Origin.Y}
			drag := listenedDrag(cursorOffset, listenedCursor, w, app)
			drag.sourcePath = path
			if !w.beginDragSession(&drag, path, app) {
				// The prevented dragstart: no drag (Chromium resets the
				// drag source and leaves the press clickable).
				dragListener = nil
				pending.event = nil
				w.requestRefresh()
				return
			}
			dragListener = nil
			*clicked = ElementClickedState{}
			app.StartDrag(drag)
			pending.event = nil
			// The drag consumed the press (browser-core ticket 12): its
			// release never clicks, so the window-level click dispatch's
			// pending press goes with the per-element one (Chromium's
			// skip_click_dispatch — a drag's up is not a click's up).
			inputState(w).pendingMouseClick = nil
			inputState(w).pressClickChain = nil
			w.requestRefresh()
			app.StopPropagation()
		})

		// The element's click and aux-click listeners register on the
		// frame under its path key (browser-core ticket 12): the window's
		// up dispatch fires them on the click's target chain — the common
		// ancestor of the press and release targets, the captured element
		// under a pointer capture — after every mouseup listener, the
		// DOM's order (mouseevent.go dispatchMouseClick; the pin fired
		// each element's click inside the up's listener traversal, the
		// recorded click-before-mouseup divergence of spec D12).
		if len(clickListeners) > 0 || len(auxClickListeners) > 0 {
			appendClickListenerRegistration(w, clickListenerRegistration{
				path:     path,
				click:    clickListeners,
				auxClick: auxClickListeners,
			})
		}

		// The mouse up clears the pending press (div.rs:3579-3599: an
		// element that moved away after the press is not on the release
		// chain, so the click dispatch's chain drops it); the window-level
		// dispatch owns the pairing, the target and the listener firing.
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isUp := event.(*MouseUpEvent); !isUp || phase != DispatchCapture {
				return
			}
			if pending.event != nil {
				pending.event = nil
				w.requestRefresh()
			}
		})
	}

	// The hover listeners (div.rs:3629-3681): a transition the stationary
	// mouse sees after a layout change is reported once the frame's
	// effects flush; a bubbled move reports transitions while no press
	// is pending and no drag is active.
	if len(d.hoverListeners) > 0 {
		if es.hoverListenerState == nil {
			es.hoverListenerState = new(bool)
		}
		wasHovered := es.hoverListenerState
		hasMouseDown := es.pendingMouseDownCell()
		listeners := slices.Clone(d.hoverListeners)
		updateHover := func(isHovered bool, w *Window, app *App) {
			if isHovered == *wasHovered {
				return
			}
			*wasHovered = isHovered
			for _, listener := range listeners {
				value := isHovered
				listener(&value, w, app)
			}
		}
		if hasMouseDown.event == nil {
			isHovered := !app.HasActiveDrag() && hitbox.IsHovered(w)
			if isHovered != *wasHovered {
				w.Defer(app, func(w *Window, app *App) { updateHover(isHovered, w, app) })
			}
		}
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isMove := event.(*MouseMoveEvent); !isMove || phase != DispatchBubble {
				return
			}
			isHovered := hasMouseDown.event == nil && !app.HasActiveDrag() && box.IsHovered(w)
			updateHover(isHovered, w, app)
		})
		// The pin also clears hover on MouseExitEvent (div.rs:3674-3680);
		// browser-core ticket 10 wires the port's platform exit event
		// (WM_MOUSELEAVE, desktop_windows.go), so the leaving window now
		// reports every hovered element's hover end, like the browser.
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isExit := event.(*MouseExitEvent); !isExit || phase != DispatchBubble {
				return
			}
			updateHover(false, w, app)
		})
	}

	// The pointer boundary listeners (browser-core ticket 10): the
	// DOM pointerenter/pointerleave sweeps drive them (hoverboundary.go).
	d.paintBoundaryListeners(hitbox, es, w, app)

	// The DOM drag-event listeners (browser-core ticket 16): the drag
	// session's dispatches drive them (dragevent.go
	// paintDragEventListeners).
	d.paintDragEventListeners(hitbox, path, w, app)

	// The pointer-capture listeners (browser-core ticket 11): the
	// gotpointercapture/lostpointercapture sweeps drive them
	// (pointercapture.go).
	d.paintCaptureListeners(hitbox, w, app)

	// The pressed state (div.rs:3725-3762): both handlers bind
	// unconditionally because the mouse up may arrive before a frame
	// renders. Browser-core ticket 11: a pointer cancel clears the
	// pressed state the same way (Chromium's pointercancel ends the
	// activation), so a press whose up went to another window leaves no
	// active style stuck.
	active := es.clicked()
	w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
		if _, isCancel := event.(*PointerCancelEvent); isCancel {
			if phase == DispatchCapture && active.isClicked() {
				*active = ElementClickedState{}
				w.requestRefresh()
			}
			return
		}
		if _, isUp := event.(*MouseUpEvent); !isUp {
			return
		}
		if phase == DispatchCapture && active.isClicked() {
			*active = ElementClickedState{}
			w.requestRefresh()
		}
	})
	var activeGroupHitbox *HitboxID
	if group := d.groupActiveStyle; group != nil {
		if id, ok := groupHitboxGet(group.Group, app); ok {
			activeGroupHitbox = &id
		}
	}
	box := hitbox
	w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
		if _, isDown := event.(*MouseDownEvent); !isDown {
			return
		}
		if phase == DispatchBubble && !w.DefaultPrevented() {
			groupHovered := activeGroupHitbox != nil && activeGroupHitbox.IsHovered(w)
			elementHovered := box.IsHovered(w)
			if groupHovered || elementHovered {
				*active = ElementClickedState{Group: groupHovered, Element: elementHovered}
				w.requestRefresh()
			}
		}
	})
}
