// prepaintActiveDragPreview is window.rs:3451-3456: the active drag's
// view is prepainted as a root at mouse_position - cursor_offset under
// min-content space, with the drag taken out of the application for the
// duration (so the preview's own elements see no active drag). The draw
// path calls it after the root prepaint and paints the returned element
// after the root paint (window.rs:3474-3475, paintActiveDragPreview).
// A drag without a view (a platform file drag) has no preview.
func prepaintActiveDragPreview(w *Window, app *App) (AnyElement, bool) {
	drag := app.activeDrag
	if drag == nil || drag.View == nil {
		return AnyElement{}, false
	}
	element := viewElementOf(drag.View)
	mouse := w.TrackedMousePosition()
	offset := Point{X: mouse.X - drag.CursorOffset.X, Y: mouse.Y - drag.CursorOffset.Y}
	app.activeDrag = nil
	defer func() { app.activeDrag = drag }()
	element.PrepaintAsRoot(offset, AvailableSize{Width: MinContentAvailableSpace(), Height: MinContentAvailableSpace()}, w, app)
	return element, true
}

