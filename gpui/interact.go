type InteractiveElementState struct {
	clickedState       *ElementClickedState
	hoverState         *ElementHoverState
	hoverListenerState *bool
	hoverBoundaryState *bool
	pendingMouseDown   *mouseDownCell
}

// clicked returns the pressed state, creating it (the pinned
// clicked_state.get_or_insert_with).
func (s *InteractiveElementState) clicked() *ElementClickedState {
	if s.clickedState == nil {
		s.clickedState = &ElementClickedState{}
	}
	return s.clickedState
}

// pendingMouseDownCell returns the pending mouse-down cell, creating it.
func (s *InteractiveElementState) pendingMouseDownCell() *mouseDownCell {
	if s.pendingMouseDown == nil {
		s.pendingMouseDown = &mouseDownCell{}
	}
	return s.pendingMouseDown
}

