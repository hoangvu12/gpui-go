// DragMoveEvent reports a mouse move while a drag of type T is active,
// to an element that registered OnDragMove (div.rs:80-103).
type DragMoveEvent[T any] struct {
	// Event is the mouse move that triggered this drag move.
	Event MouseMoveEvent
	// Bounds are the bounds of the listening element.
	Bounds Bounds
	// draggedItem is the active drag's value.
	draggedItem any
}

// Drag returns the active drag's value (div.rs:92-97 DragMoveEvent::drag).
// It panics when the stored active drag is not of type T, like the
// pin's expect.
func (e *DragMoveEvent[T]) Drag(app *App) T {
	if app != nil && app.activeDrag != nil {
		if value, ok := app.activeDrag.Value.(T); ok {
			return value
		}
	}
	panic("gpui: DragMoveEvent is only valid when the stored active drag is of the same type")
}

// DraggedItem returns the item about to be dropped (div.rs:100-102).
func (e *DragMoveEvent[T]) DraggedItem() any { return e.draggedItem }

