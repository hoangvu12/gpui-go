// ElementClickedState reports whether the element, or a group containing
// it, is pressed by the mouse (div.rs:4188-4202).
type ElementClickedState struct {
	// Group reports the element's group is pressed.
	Group bool
	// Element reports the element itself is pressed.
	Element bool
}

// isClicked is div.rs:4199 ElementClickedState::is_clicked.
func (s ElementClickedState) isClicked() bool { return s.Group || s.Element }

// ElementHoverState reports whether the element, or a group containing
// it, is hovered (div.rs:4204-4212).
type ElementHoverState struct {
	// Group reports the element's group is hovered.
	Group bool
	// Element reports the element itself is hovered.
	Element bool
}

// groupIsActive is div.rs:4215-4217.
func (s ElementHoverState) groupIsActive(w *Window) bool {
	// Browser-core ticket 10 (D12): hover survives typing, so the
	// retained hover state no longer consults the keyboard modality
	// (Chromium's :hover has no keyboard link); the touch suppression
	// stays (window.rs is_hovered's touch half).
	return s.Group && !lastInputWasTouch(w)
}

// elementIsActive is div.rs:4219-4221.
func (s ElementHoverState) elementIsActive(w *Window) bool {
	return s.Element && !lastInputWasTouch(w)
}

// mouseDownCell is the shared pending-mouse-down cell (the pinned
