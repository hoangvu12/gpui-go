// registerDivKeyboardClick is div.rs:3512-3577: while the element's
// tracked focus handle is focused, an unmodified Enter/Space key down
// records the window's focus generation, and the matching unmodified
// Enter/Space key up fires a Keyboard click when no other key event
// intervened and focus never moved; releasing any other key cancels the
// pending activation. Both listeners run in the bubble phase and honor
// prevent-default. The pin registers them inside paint_mouse_listeners
// (stateful, with a hitbox and a click / aux-click / drag listener); the
// port registers them on the div's dispatch node during prepaint.
func registerDivKeyboardClick(w *Window, d *DivElement, hitbox Hitbox, es *InteractiveElementState) {
	if es == nil || (len(d.clickListeners) == 0 && len(d.auxClickListeners) == 0 && d.dragListener == nil) {
		return
	}
	if d.focusHandle == nil || !d.focusHandle.IsFocused(w) {
		return
	}
	pending := es.pendingKeyboardDownCell()
	clickListeners := slices.Clone(d.clickListeners)
	bounds := hitbox.Bounds
	tree := currentDispatchTree(w)
	tree.OnKeyEvent(true, false, func(event *KeyDownEvent, w *Window, app *App) {
		if w.DefaultPrevented() {
			return
		}
		stroke := event.Keystroke
		isActivationKey := (stroke.Key == "enter" || stroke.Key == "space") && !stroke.Modifiers.Modified()
		if isActivationKey {
			generation := w.FocusGeneration()
			pending.generation = &generation
		} else {
			pending.generation = nil
		}
	})
	tree.OnKeyEvent(false, false, func(event *KeyUpEvent, w *Window, app *App) {
		if w.DefaultPrevented() {
			return
		}
		stroke := event.Keystroke
		var button KeyboardButton
		isActivation := true
		switch stroke.Key {
		case "enter":
			button = KeyboardButtonEnter
		case "space":
			button = KeyboardButtonSpace
		default:
			isActivation = false
		}
		if isActivation && !stroke.Modifiers.Modified() {
			generation := pending.generation
			pending.generation = nil
			if generation == nil || *generation != w.FocusGeneration() {
				return
			}
			click := ClickEvent{Kind: ClickEventKeyboard, Keyboard: KeyboardClickEvent{Button: button, Bounds: bounds}}
			for _, listener := range clickListeners {
				listener(&click, w, app)
			}
		} else {
			// Releasing any other key mid-press means this isn't a clean
			// activation, so cancel the pending keydown.
			pending.generation = nil
		}
	})
}

// paintMouseListeners is div.rs:3253-3764 paint_mouse_listeners, bounded
// to the port's features (mouse pressure / exit listeners, drop
// predicates and drag-over styles, and tooltips are not ported; the
// keyboard click registers at prepaint, registerDivKeyboardClick).
func (d *DivElement) paintMouseListeners(hitbox Hitbox, es *InteractiveElementState, w *Window, app *App) {
	// A focusable element transfers focus on a hovered mouse down unless
	// the default action was prevented (div.rs:3266-3282).
	if d.focusHandle != nil {
		handle := *d.focusHandle
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isDown := event.(*MouseDownEvent); !isDown {
				return
			}
			if phase == DispatchBubble && box.IsHovered(w) && !w.DefaultPrevented() {
				w.Focus(handle)
				// If there is a parent that is also focusable, prevent it
				// from transferring focus because we already did so.
				w.PreventDefault()
			}
		})
	}

	// The typed mouse-family listeners (div.rs:3284-3331: the
	// registration closure captures this element's hitbox and forwards
	// the phase; the listener decides what the hitbox gates).
	for _, listener := range d.mouseDownListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.mouseUpListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.mouseMoveListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.scrollWheelListeners {
		registerMouseListener(w, listener, hitbox)
	}
	for _, listener := range d.pinchListeners {
		registerMouseListener(w, listener, hitbox)
	}

	// The hover-state tracker (div.rs:3333-3358): a captured mouse move
	// that flips the element's hover updates the retained hover state
	// and notifies the current view.
	_, hasBaseCursor := d.Styled.storage().MouseCursor.Get()
	if d.hoverStyle != nil || hasBaseCursor {
		var hoverState *ElementHoverState
		if d.hoverStyle != nil && es != nil {
			hoverState = es.hoverState
		}
		notify := currentViewNotifier(w)
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isMove := event.(*MouseMoveEvent); !isMove {
				return
			}
			hovered := box.IsHovered(w)
			wasHovered := hoverState != nil && hoverState.Element
			if phase == DispatchCapture && hovered != wasHovered && hoverState != nil {
				hoverState.Element = hovered
				notify(w, app)
			}
		})
	}

	// The group-hover tracker (div.rs:3360-3381).
	if group := d.groupHoverStyle; group != nil {
		if id, ok := groupHitboxGet(group.Group, app); ok {
			var hoverState *ElementHoverState
			if es != nil {
				hoverState = es.hoverState
			}
			notify := currentViewNotifier(w)
			w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
				if _, isMove := event.(*MouseMoveEvent); !isMove {
					return
				}
				groupHovered := id.IsHovered(w)
				wasGroupHovered := hoverState != nil && hoverState.Group
				if phase == DispatchCapture && groupHovered != wasGroupHovered && hoverState != nil {
					hoverState.Group = groupHovered
					notify(w, app)
				}
			})
		}
	}

	var dragCursorStyle *CursorStyle
	if cursor, ok := d.Styled.storage().MouseCursor.Get(); ok {
		dragCursorStyle = &cursor
	}
	dragListener := d.dragListener
	clickListeners := slices.Clone(d.clickListeners)
	auxClickListeners := slices.Clone(d.auxClickListeners)

	// The drop listeners (div.rs:3391-3445): on a bubbled mouse up with an
	// active drag whose value matches a listener's payload type and this
	// element hovered (the default eligibility without can_drop
	// predicates), stop the drag, deliver the value, refresh and stop
	// propagation.
	if len(d.dropListeners) > 0 {
		listeners := append([]typedDropListener(nil), d.dropListeners...)
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			up, isUp := event.(*MouseUpEvent)
			if !isUp || phase != DispatchBubble {
				return
			}
			drag := app.ActiveDrag()
			if drag == nil {
				return
			}
			for _, listener := range listeners {
				if !dropListenerPayloadMatches(drag.Value, listener.payloadType) {
					continue
				}
				if !box.IsHovered(w) {
					continue
				}
				value, _ := app.StopDrag(w)
				listener.onDrop(value, up, w, app)
				w.requestRefresh()
				app.StopPropagation()
				break
			}
		})
	}

	if es == nil {
		return
	}

	if len(clickListeners) > 0 || len(auxClickListeners) > 0 || dragListener != nil {
		pending := es.pendingMouseDownCell()
		clicked := es.clicked()
		box := hitbox
		hasAuxClickListeners := len(auxClickListeners) > 0

		// A hovered left press (any press with aux-click listeners)
		// becomes the pending mouse down (div.rs:3467-3480).
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			down, isDown := event.(*MouseDownEvent)
			if !isDown {
				return
			}
			if phase == DispatchBubble && (down.Button == MouseButtonLeft || hasAuxClickListeners) && box.IsHovered(w) {
				pressed := *down
				pending.event = &pressed
				w.requestRefresh()
			}
		})

		// A bubbled move past the drag threshold with the left button
		// pending starts the drag once (div.rs:3482-3510).
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			move, isMove := event.(*MouseMoveEvent)
			if !isMove || phase == DispatchCapture || dragListener == nil {
				return
			}
			mouseDown := pending.event
			if mouseDown == nil {
				return
			}
			if app.HasActiveDrag() || mouseDown.Button != MouseButtonLeft {
				return
			}
			dx := float64(move.Position.X - mouseDown.Position.X)
			dy := float64(move.Position.Y - mouseDown.Position.Y)
			if math.Hypot(dx, dy) <= dragThreshold {
				return
			}
			listener := dragListener
			dragListener = nil
			*clicked = ElementClickedState{}
			cursorOffset := Point{X: move.Position.X - box.Bounds.Origin.X, Y: move.Position.Y - box.Bounds.Origin.Y}
			drag := listener(cursorOffset, dragCursorStyle, w, app)
			app.StartDrag(drag)
			pending.event = nil
			w.requestRefresh()
			app.StopPropagation()
		})

		// The mouse up pairs with the pending down (div.rs:3579-3626): the
		// capture phase takes the pending down when the element is still
		// hovered (and drops it otherwise, so an element that moved after
		// the press is not clicked), the bubble phase fires the click.
		var capturedMouseDown *MouseDownEvent
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			up, isUp := event.(*MouseUpEvent)
			if !isUp {
				return
			}
			switch phase {
			case DispatchCapture:
				if pending.event != nil && box.IsHovered(w) {
					capturedMouseDown = pending.event
					pending.event = nil
					w.requestRefresh()
				} else if pending.event != nil {
					pending.event = nil
					w.requestRefresh()
				}
			case DispatchBubble:
				if capturedMouseDown == nil {
					return
				}
				mouseDown := *capturedMouseDown
				capturedMouseDown = nil
				click := ClickEvent{Kind: ClickEventMouse, Mouse: MouseClickEvent{Down: mouseDown, Up: *up}}
				if mouseDown.Button == MouseButtonLeft {
					for _, listener := range clickListeners {
						listener(&click, w, app)
					}
				} else {
					for _, listener := range auxClickListeners {
						listener(&click, w, app)
					}
				}
			}
		})
	}

	// The hover listeners (div.rs:3629-3681): a transition the stationary
	// mouse sees after a layout change is reported once the frame's
	// effects flush; a bubbled move reports transitions while no press
	// is pending and no drag is active.
	if len(d.hoverListeners) > 0 {
		if es.hoverListenerState == nil {
			es.hoverListenerState = new(bool)
		}
		wasHovered := es.hoverListenerState
		hasMouseDown := es.pendingMouseDownCell()
		listeners := slices.Clone(d.hoverListeners)
		updateHover := func(isHovered bool, w *Window, app *App) {
			if isHovered == *wasHovered {
				return
			}
			*wasHovered = isHovered
			for _, listener := range listeners {
				value := isHovered
				listener(&value, w, app)
			}
		}
		if hasMouseDown.event == nil {
			isHovered := !app.HasActiveDrag() && hitbox.IsHovered(w)
			if isHovered != *wasHovered {
				w.Defer(app, func(w *Window, app *App) { updateHover(isHovered, w, app) })
			}
		}
		box := hitbox
		w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
			if _, isMove := event.(*MouseMoveEvent); !isMove || phase != DispatchBubble {
				return
			}
			isHovered := hasMouseDown.event == nil && !app.HasActiveDrag() && box.IsHovered(w)
			updateHover(isHovered, w, app)
		})
		// The pin also clears hover on MouseExitEvent (div.rs:3674-3680);
		// the port's platform input has no mouse-exited event yet.
	}

	// The pressed state (div.rs:3725-3762): both handlers bind
	// unconditionally because the mouse up may arrive before a frame
	// renders.
	active := es.clicked()
	w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
		if _, isUp := event.(*MouseUpEvent); !isUp {
			return
		}
		if phase == DispatchCapture && active.isClicked() {
			*active = ElementClickedState{}
			w.requestRefresh()
		}
	})
	var activeGroupHitbox *HitboxID
	if group := d.groupActiveStyle; group != nil {
		if id, ok := groupHitboxGet(group.Group, app); ok {
			activeGroupHitbox = &id
		}
	}
	box := hitbox
	w.OnMouseEvent(func(event any, phase DispatchPhase, w *Window, app *App) {
		if _, isDown := event.(*MouseDownEvent); !isDown {
			return
		}
		if phase == DispatchBubble && !w.DefaultPrevented() {
			groupHovered := activeGroupHitbox != nil && activeGroupHitbox.IsHovered(w)
			elementHovered := box.IsHovered(w)
			if groupHovered || elementHovered {
				*active = ElementClickedState{Group: groupHovered, Element: elementHovered}
				w.requestRefresh()
			}
		}
	})
}
