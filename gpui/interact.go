// KeyboardButton is the keyboard key that triggered a keyboard click
// (interactive.rs:441-449; Enter is the default).
type KeyboardButton uint8

// Keyboard click buttons.
const (
	// KeyboardButtonEnter is the Enter key.
	KeyboardButtonEnter KeyboardButton = iota
	// KeyboardButtonSpace is the Space key.
	KeyboardButtonSpace
)

// MouseClickEvent is a click generated by a mouse button pressed and
// released over the same element (interactive.rs:218-226).
type MouseClickEvent struct {
	// Down is the mouse event when the button was pressed.
	Down MouseDownEvent
	// Up is the mouse event when the button was released.
	Up MouseUpEvent
}

// KeyboardClickEvent is a click generated by a keyboard key pressed and
// released on a focused element (interactive.rs:262-270).
type KeyboardClickEvent struct {
	// Button is the key that triggered the click.
	Button KeyboardButton
	// Bounds are the bounds of the clicked element.
	Bounds Bounds
}

// TouchClickEvent is a click generated by a recognized tap gesture
// (interactive.rs:272-285). The Windows port has no touch input source,
// so no click of this kind is produced yet; the variant keeps the
// pinned accessor semantics complete.
type TouchClickEvent struct {
	// Position is the tap position in window coordinates.
	Position Point
	// TapCount is the number of consecutive taps (double tap = 2).
	TapCount int
	// LongPress reports a long press rather than a tap.
	LongPress bool
}

// ClickEventKind selects the ClickEvent variant (interactive.rs:290-297).
type ClickEventKind uint8

// Click event kinds. Keyboard is the zero value because the pinned
// ClickEvent::default() is Keyboard(KeyboardClickEvent::default())
// (interactive.rs:299-303).
const (
	// ClickEventKeyboard is a keyboard activation click.
	ClickEventKeyboard ClickEventKind = iota
	// ClickEventMouse is a mouse button click.
	ClickEventMouse
	// ClickEventTouch is a tap gesture click.
	ClickEventTouch
)

// String renders the kind for diagnostics and transcripts.
func (k ClickEventKind) String() string {
	switch k {
	case ClickEventKeyboard:
		return "Keyboard"
	case ClickEventMouse:
		return "Mouse"
	case ClickEventTouch:
		return "Touch"
	}
	return "Unknown"
}

// ClickEvent is the payload of OnClick / OnAuxClick listeners
// (interactive.rs:287-297): Kind selects which of Mouse, Keyboard or
// Touch is meaningful.
type ClickEvent struct {
	// Kind selects the variant.
	Kind ClickEventKind
	// Mouse is the Mouse variant's payload.
	Mouse MouseClickEvent
	// Keyboard is the Keyboard variant's payload.
	Keyboard KeyboardClickEvent
	// Touch is the Touch variant's payload.
	Touch TouchClickEvent
}

// Modifiers returns the modifiers held during the click: the mouse-up's
// modifiers for a mouse click, none for keyboard and touch clicks
// (interactive.rs:310-321).
func (e *ClickEvent) Modifiers() Modifiers {
	if e.Kind == ClickEventMouse {
		return e.Mouse.Up.Modifiers
	}
	return Modifiers{}
}

// Position returns the click position: the bottom-left corner of the
// clicked bounds for a keyboard click, the mouse-up position for a mouse
// click, the tap position for a touch click (interactive.rs:328-334).
func (e *ClickEvent) Position() Point {
	switch e.Kind {
	case ClickEventMouse:
		return e.Mouse.Up.Position
	case ClickEventTouch:
		return e.Touch.Position
	}
	return e.Keyboard.Bounds.BottomLeft()
}

// MousePosition returns the mouse-up position of a mouse click; keyboard
// and touch clicks report none (interactive.rs:341-347).
func (e *ClickEvent) MousePosition() (Point, bool) {
	if e.Kind == ClickEventMouse {
		return e.Mouse.Up.Position, true
	}
	return Point{}, false
}

// IsRightClick reports a right button pressed and released
// (interactive.rs:353-361).
func (e *ClickEvent) IsRightClick() bool {
	return e.Kind == ClickEventMouse && e.Mouse.Down.Button == MouseButtonRight && e.Mouse.Up.Button == MouseButtonRight
}

// IsMiddleClick reports a middle button pressed and released
// (interactive.rs:367-375).
func (e *ClickEvent) IsMiddleClick() bool {
	return e.Kind == ClickEventMouse && e.Mouse.Down.Button == MouseButtonMiddle && e.Mouse.Up.Button == MouseButtonMiddle
}

// IsSecondary reports a secondary activation: a right click, or a touch
// long press (interactive.rs:381-389).
func (e *ClickEvent) IsSecondary() bool {
	switch e.Kind {
	case ClickEventMouse:
		return e.Mouse.Down.Button == MouseButtonRight && e.Mouse.Up.Button == MouseButtonRight
	case ClickEventTouch:
		return e.Touch.LongPress
	}
	return false
}

// StandardClick reports a standard click: every keyboard click, a left
// mouse click, a tap that is not a long press (interactive.rs:396-404).
func (e *ClickEvent) StandardClick() bool {
	switch e.Kind {
	case ClickEventMouse:
		return e.Mouse.Down.Button == MouseButtonLeft && e.Mouse.Up.Button == MouseButtonLeft
	case ClickEventTouch:
		return !e.Touch.LongPress
	}
	return true
}

// FirstFocus reports whether a mouse click was the window's first,
// focusing click (interactive.rs:411-417).
func (e *ClickEvent) FirstFocus() bool {
	return e.Kind == ClickEventMouse && e.Mouse.Down.FirstMouse
}

// ClickCount returns the click count: 1 for keyboard clicks, the
// mouse-up's count for mouse clicks, the tap count for touch clicks
// (interactive.rs:424-430).
func (e *ClickEvent) ClickCount() int {
	switch e.Kind {
	case ClickEventMouse:
		return e.Mouse.Up.ClickCount
	case ClickEventTouch:
		return e.Touch.TapCount
	}
	return 1
}

// IsKeyboard reports a keyboard-generated click (interactive.rs:433-438).
func (e *ClickEvent) IsKeyboard() bool { return e.Kind == ClickEventKeyboard }

