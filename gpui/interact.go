// cursorRequestFrame returns the frame under construction, panicking
// outside a draw (the pinned debug_assert_paint).
func cursorRequestFrame(w *Window, what string) *renderedFrame {
	if w == nil {
		panic(fmt.Sprintf("gpui: %s requires a live window", what))
	}
	fs := focusState(w)
	if fs.next == nil {
		panic(fmt.Sprintf("gpui: %s requires a frame under construction (paint)", what))
	}
	return fs.next
}

// appendCursorRequest records one request on the frame under
// construction, dropping requests of frames that are neither rendered
// nor being built.
func appendCursorRequest(w *Window, frame *renderedFrame, request cursorStyleRequest) {
	st := interactStateOf(w)
	for i := range st.cursorFrames {
		if st.cursorFrames[i].frame == frame {
			st.cursorFrames[i].requests = append(st.cursorFrames[i].requests, request)
			return
		}
	}
	rendered := focusState(w).rendered
	kept := st.cursorFrames[:0]
	for _, f := range st.cursorFrames {
		if f.frame == rendered {
			kept = append(kept, f)
		}
	}
	st.cursorFrames = append(kept, frameCursorRequests{frame: frame, requests: []cursorStyleRequest{request}})
}

// SetCursorStyle requests the cursor shown while the hitbox is hovered
// (window.rs:3844-3850 set_cursor_style). Paint phase only.
func (w *Window) SetCursorStyle(style CursorStyle, hitbox *Hitbox) {
	if hitbox == nil {
		panic("gpui: SetCursorStyle requires a hitbox")
	}
	frame := cursorRequestFrame(w, "SetCursorStyle")
	appendCursorRequest(w, frame, cursorStyleRequest{hitboxID: hitbox.id, hasHitbox: true, style: style})
}

// SetWindowCursorStyle requests the cursor for the whole window, taking
// precedence over every hitbox request (window.rs:3856-3862
// set_window_cursor_style). Paint phase only.
func (w *Window) SetWindowCursorStyle(style CursorStyle) {
	frame := cursorRequestFrame(w, "SetWindowCursorStyle")
	appendCursorRequest(w, frame, cursorStyleRequest{style: style})
}

// frameCursorStyle is window.rs:1200-1213 Frame::cursor_style: walking
// the requests newest first, a window request wins outright; otherwise
// the newest request whose hitbox is hovered (ignoring the keyboard
// modality) decides.
func frameCursorStyle(w *Window, frame *renderedFrame) (CursorStyle, bool) {
	st, ok := interactWindowStates[w]
	if !ok || frame == nil {
		return CursorArrow, false
	}
	for _, f := range st.cursorFrames {
		if f.frame != frame {
			continue
		}
		var found *CursorStyle
		for i := len(f.requests) - 1; i >= 0; i-- {
			request := f.requests[i]
			if !request.hasHitbox {
				return request.style, true
			}
			if found == nil && HitboxID(request.hitboxID).isHoveredIgnoringLastInput(w) {
				style := request.style
				found = &style
			}
		}
		if found != nil {
			return *found, true
		}
		return CursorArrow, false
	}
	return CursorArrow, false
}

// resetCursorStyle is window.rs:5684-5693 reset_cursor_style: the
// rendered frame's cursor (the arrow when no request applies) goes to
// the platform when the window owns the mouse cursor. The resolved
// style is also recorded for the test-support observable.
func (w *Window) resetCursorStyle(app *App) {
	style, ok := frameCursorStyle(w, focusState(w).rendered)
	if !ok {
		style = CursorArrow
	}
	st := interactStateOf(w)
	st.resolvedCursor, st.resolvedCursorSet = style, true
	if windowOwnsCursor(w) {
		setPlatformCursorStyle(app, style)
	}
}

// windowOwnsCursor and setPlatformCursorStyle are reset_cursor_style's
// platform boundary (window.rs:5686 is_window_hovered, :5691
// cx.platform.set_cursor_style). The defaults ask the attached host —
// Host.SetCursorStyle then posts WM_GPUI_CURSOR_STYLE_CHANGED and the
// window's WM_SETCURSOR shows the handle (platform.rs:780-790,
// events.rs:1170-1211). Tests substitute recorders so the hovered
// element's cursor is observed where it leaves for the platform,
// without a real window.
var (
	windowOwnsCursor       = func(w *Window) bool { return w.isWindowHovered() }
	setPlatformCursorStyle = func(app *App, style CursorStyle) { _ = app.SetCursorStyle(style) }
)

// resolvedCursorStyle reports the cursor the last reset resolved (test
// support).
func resolvedCursorStyle(w *Window) (CursorStyle, bool) {
	st, ok := interactWindowStates[w]
	if !ok || !st.resolvedCursorSet {
		return CursorArrow, false
	}
	return st.resolvedCursor, true
}

// WindowCursorStyle reports the cursor the window last resolved from its
// rendered frame's cursor requests against the hovered hitboxes
// (window.rs:1200-1213 Frame::cursor_style, the arrow when no request
// applies; reset_cursor_style runs at the end of every frame and when a
// mouse event changes the hit test). It is the style a hovered real
// window hands to the platform; test windows are never hovered (the
// pin's TestWindow::is_hovered is false), so this is their observable.
// ok is false before the first reset.
func WindowCursorStyle(w *Window) (style CursorStyle, ok bool) {
	return resolvedCursorStyle(w)
}

// isWindowHovered is window.rs:2791-2801 is_window_hovered on Windows:
// the platform window's hovered state (test windows have no platform
// cursor).
func (w *Window) isWindowHovered() bool {
	if w.handle.host == nil {
		return false
	}
	hovered, err := w.handle.IsHovered()
	return err == nil && hovered
}

