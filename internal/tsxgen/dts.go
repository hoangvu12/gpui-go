package tsxgen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// DTS renders the surface as the gpui-script.d.ts ambient declarations:
// the JSX elements and their props, the CSSProperties style object,
// the DOM-shaped event, the host's globals, and the Tailwind class
// type — everything a .tsx view can use, nothing more.
//
// The layout is canonical (sorted, one arm per line) so the committed
// file is byte-stable across regenerations and ParseDTS can read it
// back for the drift tests.
func (s *Surface) DTS() string {
	var b strings.Builder
	b.WriteString(dtsHeader)

	// The shared class aliases, then Class.
	for _, a := range s.Classes.Aliases {
		writeType(&b, a.Name, a.Type, "")
	}
	writeType(&b, "Class", s.Classes.Class, classDoc)

	// The JSX elements. The slot element is the plugin seam (ticket
	// 67): a div-like container whose children the slot registry owns,
	// so it takes the shared props plus its name — declared separately
	// (SlotProps below) because name is a slot-only prop.
	b.WriteString("\n// The host elements: div and text (a text run), plus Fragment, whose\n// children lower as their parent's direct children (no wrapper), and\n// slot — the plugin seam: a container whose children the slot\n// registry owns (ticket 67).\ninterface HostElement {}\n\ndeclare namespace JSX {\n\tinterface Element extends HostElement {}\n\tinterface IntrinsicElements {\n")
	for _, el := range sortedCopy(s.Elements) {
		props := "HostProps"
		if p, ok := elementPropTypes[el]; ok {
			props = p
		}
		fmt.Fprintf(&b, "\t\t%s: %s;\n", el, props)
	}
	b.WriteString("\t}\n}\n")

	// The element props. className stays string: a class list is
	// space-separated and open-ended, and the engine validates every
	// class at load (a bad class is a load error with the .tsx file and
	// line — the same check Styled.Class runs). The Class type above is
	// the single-class surface; use it where a single class is built.
	b.WriteString("\ninterface HostProps {\n")
	for _, p := range sortedCopy(s.Props) {
		fmt.Fprintf(&b, "\t%s?: %s;\n", p, propType(p))
	}
	b.WriteString("}\n")

	// The plugin surface (ticket 67): the slot element's own props and
	// the plugin manifest a plugin bundle exports. Fixed shapes, like
	// the fetch types below: the extraction covers the element (the
	// engine's element switch) while the manifest is the host's entry
	// contract, stated here so plugin authors and the checker agree.
	b.WriteString(pluginDTS)

	// The event handlers receive (the DOM-shaped event object).
	b.WriteString("\n// The event object handlers receive (DOM-shaped: the mouse button as\n// the DOM's numbers, the position in window px, the modifier keys).\ninterface MouseEvent {\n")
	for _, f := range s.Event {
		fmt.Fprintf(&b, "\t%s: %s;\n", f.Name, f.Type.Render())
	}
	b.WriteString("}\n")

	// The style object.
	b.WriteString("\n// The style object's CSS properties (camelCase, as in React), with the\n// value shapes the engine accepts; anything else is a load error that\n// names the .tsx line.\ninterface CSSProperties {\n")
	for _, sp := range s.Styles {
		if sp.Doc != "" {
			fmt.Fprintf(&b, "\t/** %s */\n\t%s?: %s;\n", sp.Doc, sp.Name, sp.Type.Render())
			continue
		}
		fmt.Fprintf(&b, "\t%s?: %s;\n", sp.Name, sp.Type.Render())
	}
	b.WriteString("}\n")

	// Children, state and the host globals.
	b.WriteString("\n// Children are elements, text, numbers, bindings, arrays and\n// false/undefined/null (skipped, so {cond && <x />} works).\ntype Child = string | number | boolean | null | undefined | HostElement | Child[];\n\n// The keyed-state handle (state and shared): set recomputes only the\n// bindings on that key, without re-describing the tree.\ninterface StateHandle<S> {\n\tkey: string;\n\tget(): S;\n\tset(value: S): void;\n}\n")
	for _, g := range s.Globals {
		sig := g.Sig
		if i := strings.Index(sig, " "); i > 0 && strings.HasPrefix(sig, "declare ") {
			_ = i
		}
		b.WriteString("\n")
		b.WriteString(sig)
		b.WriteString("\n")
	}

	// The fetch types.
	b.WriteString("\ninterface RequestInit {\n\tmethod?: string;\n\theaders?: Record<string, string>;\n\tbody?: string | object;\n}\n\ninterface Response {\n\tstatus: number;\n\tok: boolean;\n\tstatusText: string;\n\theaders: Record<string, string>;\n\turl: string;\n\ttext(): Promise<string>;\n\tjson(): Promise<any>;\n}\n\ninterface Console {\n\tlog(...data: any[]): void;\n\tinfo(...data: any[]): void;\n\tdebug(...data: any[]): void;\n\twarn(...data: any[]): void;\n\terror(...data: any[]): void;\n\ttrace(...data: any[]): void;\n\tassert(condition?: boolean, ...data: any[]): void;\n}\n")
	return b.String()
}

// dtsHeader is the file banner and the entry contracts (the app's App,
// the plugin's ` + "`plugin`" + ` manifest — ticket 67).
const dtsHeader = `// Code generated by cmd/tsxdtsgen from the engine's own source; DO NOT EDIT.
//
// The TSX authoring surface of gpui-go's script host (ADR 0003):
// the JSX elements, the style object's CSS properties, the events and
// the host globals the engine accepts, and the Tailwind class surface
// (generated from the class layer's tables — gpui/class_generated.go,
// gpui/class.go, gpui/tailwind_palette_generated.go).
//
// A test regenerates this file and fails when the engine and the types
// drift in either direction (internal/tsxgen). Type-check a view with
// cmd/tsxcheck (tsc), and reload-type-check with script.WithTypeCheck.
//
// An app's entry module exports a function component named App:
//
//	export function App() {
//		return <div className="flex items-center gap-2">Hello!</div>;
//	}
//
// A plugin bundle instead exports a ` + "`plugin`" + ` manifest naming the slots
// it fills (ticket 67; the PluginManifest interface below):
//
//	export function Main() { return <div>...</div>; }
//	export const plugin: PluginManifest = { slots: { main: Main } };
`

// elementPropTypes names the elements whose props differ from the
// shared HostProps. The slot element takes the shared props plus its
// name (SlotProps, in the plugin section below); the name is parsed
// outside the engine's shared prop switch, so it is a slot-only prop.
var elementPropTypes = map[string]string{
	"slot": "SlotProps",
}

// pluginDTS is the plugin authoring surface (ticket 67): the slot
// element's props, the slot components' props and the manifest a
// plugin bundle exports. Interfaces only, on purpose: the drift
// parser reads type declarations as unions of literals, so everything
// here is an interface it deliberately ignores (the same treatment as
// the fetch and console types).
const pluginDTS = `
// The slot element (the app side of plugins): a div-like container
// whose children the slot registry owns — the plugins registered for
// its name contribute them, in registration order; its JSX children
// are the fallback shown while no plugin fills it (a web component's
// slot).
interface SlotProps extends HostProps {
	/** The slot's name: which plugins' contributions fill it. */
	name: string;
}

// A slot component receives the name of the slot instance it fills.
interface PluginSlotProps {
	/** The name of the slot this component was called for. */
	slot: string;
}

// A slot component: called once per (re)load and per re-describe, it
// describes that slot's content (an element tree, like App).
interface SlotComponent {
	(props: PluginSlotProps): HostElement;
}

// The manifest a plugin bundle exports as its entry: the slots it
// fills, by name, and the component describing each. The app grants
// what the plugin may reach (script.Slots' Grants); a plugin reaching
// past its grants gets a named error.
interface PluginManifest {
	/** The slots this plugin contributes to, keyed by slot name. */
	slots: Record<string, SlotComponent>;
}
`

// classDoc documents the Class type.
const classDoc = `The Tailwind classes the engine's class layer accepts (generated
from its tables; the drift tests keep it in sync with
gpui.CheckClasses). Every palette color, scale value, bracketed
length and opacity modifier is included; the engine additionally
accepts any spacing-scale number (${number} here also matches
exponent and non-0.25 forms the engine rejects at load) and any
fraction. A variant or ! prefix composes over any class and a
className is a space-separated list — both open forms the engine
validates at load, reporting the .tsx file and line — so use Class
where a single class is built and let the load-time check police
lists and prefixed forms.`

// propType maps a prop name to its TS type.
func propType(p string) string {
	switch p {
	case "key", "id":
		return "string"
	case "className":
		return "string"
	case "style":
		return "CSSProperties"
	case "children":
		return "Child | Child[]"
	default:
		if strings.HasPrefix(p, "on") {
			return "(event: MouseEvent) => void"
		}
		return "any"
	}
}

// writeType renders one `type Name = ...` declaration with its arms
// one per line (the canonical layout ParseDTS reads back).
func writeType(b *strings.Builder, name string, t TSType, doc string) {
	if doc != "" {
		b.WriteString("\n/**\n")
		for _, line := range strings.Split(doc, "\n") {
			fmt.Fprintf(b, " * %s\n", line)
		}
		b.WriteString(" */\n")
	} else {
		b.WriteString("\n")
	}
	arms := typeArms(t)
	if len(arms) == 0 {
		fmt.Fprintf(b, "type %s = never;\n", name)
		return
	}
	fmt.Fprintf(b, "type %s =\n", name)
	for i, arm := range arms {
		if i == len(arms)-1 {
			fmt.Fprintf(b, "\t%s;\n", arm)
			break
		}
		fmt.Fprintf(b, "\t%s |\n", arm)
	}
}

// typeArms renders the type's arms in canonical order: literals, then
// numeric literals, then references, then the keywords, then the
// templates in declaration order.
func typeArms(t TSType) []string {
	var arms []string
	for _, lit := range t.Literals {
		arms = append(arms, strconv.Quote(lit))
	}
	arms = append(arms, t.NumLits...)
	arms = append(arms, t.Refs...)
	if t.Number {
		arms = append(arms, "number")
	}
	if t.Str {
		arms = append(arms, "string")
	}
	if t.Bool {
		arms = append(arms, "boolean")
	}
	for _, tmpl := range t.Templates {
		arms = append(arms, tmpl.String())
	}
	return arms
}

func sortedCopy(ss []string) []string {
	out := append([]string(nil), ss...)
	sort.Strings(out)
	return out
}
