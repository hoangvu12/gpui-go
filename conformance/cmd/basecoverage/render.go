package main

import (
	"fmt"
	"sort"
	"strings"
)

// renderMarkdown writes the human summary (evidence/base/COVERAGE.md).
func renderMarkdown(l *ledger) string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	t := l.Totals
	p("# GPUI Base coverage\n\n")
	p("Generated by `%s` from `evidence/base/source-manifest.json` (%s @ `%s`, crates/base). Do not edit by hand; the full ledger is [coverage-ledger.json](coverage-ledger.json).\n\n", l.Generator, l.Repository, l.Commit[:8])
	p("Manifest: %d files, %d sha256-verified, %d mismatched.\n\n", l.ManifestFiles, l.ManifestCheck.Verified, len(l.ManifestCheck.Mismatches))
	p("## Totals\n\n")
	p("| | Total | Ported | Deviated | Not applicable | Out of scope | Deferred | GAP |\n|---|---|---|---|---|---|---|---|\n")
	row := func(name string, c counts) {
		p("| %s | %d | %d | %d | %d | %d | %d | %d |\n", name, c.Total, c.Ported, c.Deviated, c.NotApplicable, c.OutOfScope, c.Deferred, c.Gap)
	}
	row("Upstream tests (all manifest .rs)", t.Tests)
	row("Upstream tests (crate: src/ + tests/)", t.TestsInCrate)
	p("\nModules (.rs files): %d —", t.Modules)
	var ks []string
	for k := range t.ModulesByStatus {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	for i, k := range ks {
		sep := ","
		if i == len(ks)-1 {
			sep = "."
		}
		p(" %s %d%s", k, t.ModulesByStatus[k], sep)
	}
	p(" Non-Rust manifest files: %d (see the ledger's `other_files`).\n\n", len(l.OtherFiles))
	p("Resolution: %d tests by a Go `U:path:line` citation, %d by the evidence table (`conformance/cmd/basecoverage/overrides.go`), the rest by module disposition (upstream examples).\n\n", t.CitedByGo, t.FromEvidence)
	p("Statuses: *ported* — a Go test ports it; *deviated* — ported with a recorded deviation; *not applicable* — not ported, with the ticket's reason; *out of scope* — upstream example apps (the Go counterpart is `examples/base-showcase`); *deferred* — owned by an open ticket (37, `request_autoscroll`).\n\n")

	p("## GAPS\n\n")
	if len(l.Gaps) == 0 {
		p("None: every upstream module and test is accounted for.\n\n")
	} else {
		for _, g := range l.Gaps {
			p("- %s\n", g)
		}
		p("\n")
	}

	p("## Modules\n\n| Upstream module | Status | Tickets | Go files | Tests | P | D | N/A | Def |\n|---|---|---|---|---|---|---|---|---|\n")
	for _, m := range l.Modules {
		if strings.HasPrefix(m.Path, "crates/base/examples/") {
			continue
		}
		p("| `%s` | %s | %s | %d | %d | %d | %d | %d | %d |\n", strings.TrimPrefix(m.Path, "crates/base/"), m.Status, strings.Join(m.Tickets, ","), len(m.GoFiles), m.Tests.Total, m.Tests.Ported, m.Tests.Deviated, m.Tests.NotApplicable, m.Tests.Deferred)
	}
	ex := counts{}
	nex := 0
	for _, m := range l.Modules {
		if strings.HasPrefix(m.Path, "crates/base/examples/") {
			nex++
			ex.Total += m.Tests.Total
		}
	}
	p("| `examples/**` (%d files) | out_of_scope | 32 | — | %d | | | | |\n\n", nex, ex.Total)

	for _, sec := range []struct{ status, title string }{
		{statusNA, "Not applicable"}, {statusDeferred, "Deferred"}, {statusGap, "GAP tests"},
	} {
		var rows []testEntry
		for _, te := range l.Tests {
			if te.Status == sec.status {
				rows = append(rows, te)
			}
		}
		if len(rows) == 0 {
			continue
		}
		p("## %s (%d)\n\n", sec.title, len(rows))
		for _, te := range rows {
			p("- `%s:%d` %s — %s\n", strings.TrimPrefix(te.Module, "crates/base/"), te.Line, te.Name, te.Reason)
		}
		p("\n")
	}
	if len(l.BeyondEOF) > 0 || len(l.UnknownCitations) > 0 {
		p("## Citation notes\n\nGo citations whose line range runs past the upstream file (stale line numbers; the tests are resolved by the evidence table where needed):\n\n")
		for _, s := range l.BeyondEOF {
			p("- %s\n", s)
		}
		for _, s := range l.UnknownCitations {
			p("- unknown upstream path: %s\n", s)
		}
		p("\n")
	}
	p("Deviated tests (%d) are listed with their citing Go test in the ledger's `tests`.\n", t.Tests.Deviated)
	return b.String()
}
